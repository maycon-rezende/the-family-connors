const key = document.body.dataset.character;
const p = profiles[key];
if (p) {
  document.title = `${p.name} ${p.surname} | Era da Extinção`;
  document.documentElement.style.setProperty('--focus', p.focus);
  document.querySelector('[data-hero]').src = p.hero;
  document.querySelector('[data-hero]').alt = `${p.name} ${p.surname} no presente`;
  document.querySelector('[data-code]').textContent = `${p.code} // ARQUIVO DO PRESENTE`;
  document.querySelector('[data-name]').innerHTML = `${p.name}<em>${p.surname}</em>`;
  document.querySelector('[data-intro]').textContent = p.intro;
  document.querySelector('[data-age]').textContent = p.age;
  document.querySelector('[data-role]').textContent = p.role;
  document.querySelector('[data-chapter-title]').innerHTML = `${p.title}<em>${p.accent}</em>`;
  document.querySelector('[data-story]').innerHTML =
    p.paragraphs.map((x) => `<p>${x}</p>`).join('') + `<p class="quote">${p.quote}</p>`;
  document.querySelector('[data-memory]').src = p.memory;
  document.querySelector('[data-memory-title]').textContent = p.memoryTitle;
  document.querySelector('[data-memory-text]').textContent = p.memoryText;
  const gallery = document.querySelector('[data-gallery]');
  if (gallery) {
    gallery.innerHTML = p.gallery
      .map(
        ([src, label]) =>
          `<figure><img src="${src}" alt="${label} — ${p.name}" loading="lazy"><figcaption>${label}</figcaption></figure>`
      )
      .join('');
  }
}

if (key === 'jack') {
  const cursor = document.querySelector('.jack-cursor');
  if (cursor && matchMedia('(pointer: fine)').matches) {
    addEventListener('pointermove', ({ clientX, clientY }) => {
      cursor.style.left = `${clientX}px`;
      cursor.style.top = `${clientY}px`;
    });
    document.querySelectorAll('a, .gallery figure, .command-console article').forEach((target) => {
      target.addEventListener('pointerenter', () => cursor.classList.add('active'));
      target.addEventListener('pointerleave', () => cursor.classList.remove('active'));
    });
  }

  const reveals = document.querySelectorAll(
    '.profile-reveal, .chapter-grid, .memory-copy, .gallery figure'
  );
  if ('IntersectionObserver' in window) {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (!entry.isIntersecting) return;
          entry.target.classList.add('is-visible');
          observer.unobserve(entry.target);
        });
      },
      { threshold: 0.12 }
    );
    reveals.forEach((item, index) => {
      item.style.transitionDelay = `${(index % 4) * 80}ms`;
      observer.observe(item);
    });
  } else {
    reveals.forEach((item) => item.classList.add('is-visible'));
  }
}
